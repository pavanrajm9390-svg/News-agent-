"""News briefing agent using Claude via LangChain (LangSmith traced)."""
import json
from datetime import datetime, timezone
from typing import List, Dict, Any

from langsmith import traceable
from providers import get_provider
from prompts.briefing import build_briefing_prompt


def parse_briefing(raw: str, provider_name: str) -> Dict[str, Any]:
    cleaned = raw.replace("```json", "").replace("```", "").strip()
    try:
        parsed = json.loads(cleaned)
    except json.JSONDecodeError as e:
        raise ValueError(f"{provider_name} returned incomplete JSON.") from e

    sections = parsed.get("sections")
    if not isinstance(sections, list) or not any(
        isinstance(s.get("stories"), list) and len(s.get("stories", [])) > 0 for s in sections
    ):
        raise ValueError(f"{provider_name} returned no stories.")
    return parsed


def to_markdown(data: Dict[str, Any]) -> str:
    md = f"# {data.get('title') or 'Daily Briefing'}\n\n"
    if data.get("summary"):
        md += f"> {data['summary']}\n\n"

    sections = data.get("sections")
    if isinstance(sections, list):
        for section in sections:
            md += f"## {section.get('category') or 'News'}\n\n"
            for story in section.get("stories") or []:
                md += f"### {story.get('headline', '')}\n"
                md += f"{story.get('summary', '')}\n\n"
                if story.get("why_it_matters"):
                    md += f"*Why it matters:* {story['why_it_matters']}\n\n"
                source = story.get("source") or "Source"
                url = story.get("url") or ""
                md += f"🔗 [{source}]({url})\n\n"
    md += "\n---\n*Generated by News Briefing Agent*"
    return md


@traceable(name="generate_news_briefing", run_type="chain")
async def run_agent(articles: List[Dict[str, Any]], options: Dict[str, Any] = None) -> Dict[str, Any]:
    options = options or {}
    provider_name = options.get("provider") or "anthropic"
    provider_fn = get_provider(provider_name)

    if not articles:
        return {
            "title": "No news today",
            "summary": "No articles were collected.",
            "sections": [],
            "selected_indexes": [],
            "markdown": "# No news available",
            "provider": provider_name,
            "generated_at": datetime.now(timezone.utc).isoformat(),
        }

    prompt = build_briefing_prompt(articles, options)
    gen_options = {"temperature": 0.35, "maxTokens": 16384}

    raw = await provider_fn(prompt, gen_options)
    parsed = parse_briefing(raw, provider_name)
    parsed["markdown"] = to_markdown(parsed)
    parsed["provider"] = provider_name
    parsed["generated_at"] = datetime.now(timezone.utc).isoformat()
    return parsed
